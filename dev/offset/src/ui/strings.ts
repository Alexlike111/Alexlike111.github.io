export type StrKey = keyof typeof D;
export const t = (k: StrKey): string => D[k][getLang()];
/** dictionary lookup with a dynamic key (kill causes, biomes); falls back to the raw id in caps */
export function tDyn(prefix: string, id: string): string {
  const e = (D as Record<string, L>)[prefix + id];
  return e ? e[getLang()] : id.toUpperCase();
}

const ROMAN = ['0', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'];
export const roman = (n: number): string => ROMAN[n] ?? String(n);
export const pad2 = (n: number): string => (n < 10 ? '0' : '') + n;
export function fmtTime(sec: number): string { const s = Math.max(0, Math.floor(sec)); return pad2(Math.floor(s / 60)) + ':' + pad2(s % 60); }
/** 12 480 — thin-space thousands, like a print-run count */
export function fmtInt(n: number): string { const s = String(Math.round(n)); return s.length > 4 ? s.replace(/\B(?=(\d{3})+(?!\d))/g, ' ') : s; }
